/** Stable API error codes for host apps / merchants. */

export const ApiErrorCode = {
  INVALID_API_KEY: 'INVALID_API_KEY',
  UNAUTHORIZED_ADMIN: 'UNAUTHORIZED_ADMIN',
  ADMIN_SECRET_MISSING: 'ADMIN_SECRET_MISSING',

  TENANT_NOT_FOUND: 'TENANT_NOT_FOUND',
  TENANT_SUSPENDED: 'TENANT_SUSPENDED',
  TENANT_USDT_EXHAUSTED: 'TENANT_USDT_EXHAUSTED',

  INVALID_BET_AMOUNT: 'INVALID_BET_AMOUNT',
  BET_OPTION_REQUIRED: 'BET_OPTION_REQUIRED',
  EXTERNAL_ID_REQUIRED: 'EXTERNAL_ID_REQUIRED',
  MERCHANT_DEBIT_FAILED: 'MERCHANT_DEBIT_FAILED',
  INSUFFICIENT_BALANCE: 'INSUFFICIENT_BALANCE',
  GAME_NOT_FOUND: 'GAME_NOT_FOUND',
  ROUND_NOT_FOUND: 'ROUND_NOT_FOUND',
  BETTING_CLOSED: 'BETTING_CLOSED',
  INVALID_AMOUNT: 'INVALID_AMOUNT',
  PLAYER_NOT_FOUND: 'PLAYER_NOT_FOUND',

  ROUND_ID_REQUIRED: 'ROUND_ID_REQUIRED',
  SESSION_FAILED: 'SESSION_FAILED',
  SETTLE_FAILED: 'SETTLE_FAILED',
  INTERNAL_ERROR: 'INTERNAL_ERROR',
  BET_FAILED: 'BET_FAILED',
} as const;

export type ApiErrorCode = (typeof ApiErrorCode)[keyof typeof ApiErrorCode];

export function apiError(
  message: string,
  status: number,
  code: ApiErrorCode,
): Error & { status: number; code: ApiErrorCode } {
  return Object.assign(new Error(message), { status, code });
}
