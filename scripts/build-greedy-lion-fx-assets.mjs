#!/usr/bin/env node
/**
 * Build the small, purpose-made Greedy Lion assets used on the cold-start path.
 *
 *   node scripts/build-greedy-lion-fx-assets.mjs
 *
 * 1. wing-spark-glow.webp — the old Phaser scene called spark.setScale(1)
 *    after setDisplaySize(), so it drew wing-spark.webp at native size behind
 *    a circular mask of diameter SPARK (slotSize × 1.28 ≈ 69 game px). Players
 *    saw only the bright center of the burst as a solid golden disc. We bake
 *    exactly that region (1:1 crop, ×3 for high-DPR, opaque inside the circle).
 * 2. bet-coin.webp — 64px copy of the fruit-party gold chip (shown ~11 game px;
 *    the shared original is 400px / 30 KB).
 * 3. splash.webp — WebP of splash.jpg (same 750px size).
 * 4. app/greedylion/splashPlaceholder.ts — ~1 KB blurred splash inlined in the
 *    HTML so the first paint is the splash art, not a flat color.
 */
import fs from 'node:fs/promises';
import sharp from 'sharp';

const DIR = 'public/greedy-lion';
const SLOT_SIZE = 54; // WHEEL.slotSize
const SPARK = Math.round(SLOT_SIZE * 1.28); // 69 game px
const SCALE = 3;

const kb = (n) => `${(n / 1024).toFixed(1)}KB`;

// 1) Win spark glow
{
  const src = `${DIR}/wing-spark.webp`;
  const meta = await sharp(src).metadata();
  const size = SPARK * SCALE;
  const { data, info } = await sharp(src)
    .extract({
      left: Math.round((meta.width - SPARK) / 2),
      top: Math.round((meta.height - SPARK) / 2),
      width: SPARK,
      height: SPARK,
    })
    .resize(size, size, { kernel: 'lanczos3' })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  // Straight color made opaque inside a 1px anti-aliased circle: Phaser's
  // WebGL path showed this region as a solid disc whatever was behind it.
  const r = size / 2;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const d = Math.hypot(x + 0.5 - r, y + 0.5 - r);
      data[(y * size + x) * info.channels + 3] = Math.round(
        255 * Math.min(1, Math.max(0, r - d)),
      );
    }
  }
  const out = await sharp(data, { raw: { width: size, height: size, channels: 4 } })
    .webp({ quality: 90, alphaQuality: 100, effort: 6 })
    .toFile(`${DIR}/wing-spark-glow.webp`);
  console.log(`✔ wing-spark-glow.webp ${out.width}x${out.height} ${kb(out.size)}`);
}

// 2) Bet coin
{
  const out = await sharp('public/fruit-party/chips/coin_gold.webp')
    .resize({ width: 64, kernel: 'lanczos3' })
    .webp({ quality: 90, alphaQuality: 100, effort: 6 })
    .toFile(`${DIR}/bet-coin.webp`);
  console.log(`✔ bet-coin.webp ${out.width}x${out.height} ${kb(out.size)}`);
}

// 3) Splash WebP
{
  const out = await sharp(`${DIR}/splash.jpg`)
    .webp({ quality: 85, effort: 6, smartSubsample: true })
    .toFile(`${DIR}/splash.webp`);
  console.log(`✔ splash.webp ${out.width}x${out.height} ${kb(out.size)}`);
}

// 4) Inline blurred placeholder
{
  const buf = await sharp(`${DIR}/splash.jpg`)
    .resize({ width: 24 })
    .blur(0.6)
    .webp({ quality: 50 })
    .toBuffer();
  const uri = `data:image/webp;base64,${buf.toString('base64')}`;
  await fs.writeFile(
    'app/greedylion/splashPlaceholder.ts',
    `// Generated by scripts/build-greedy-lion-fx-assets.mjs — do not edit.\n` +
      `/** ~1 KB blurred splash.jpg, inlined so the first paint shows the art. */\n` +
      `export const SPLASH_PLACEHOLDER =\n  '${uri}';\n`,
  );
  console.log(`✔ splashPlaceholder.ts ${uri.length} chars`);
}
